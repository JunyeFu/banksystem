'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {HarnessDatabase}=require('../../dist/harness/src/database.js');
const {startHarness}=require('../../dist/harness/src/server.js');
const {chromium}=require('../../runtime/node_modules/playwright');
test('Quality rendered pagination and global search use the real isolated Harness',async t=>{
  const productRoot=path.resolve(__dirname,'../..');
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'rf057-quality-browser-'));
  const databasePath=path.join(root,'data.sqlite');
  const migrationsDirectory=path.join(productRoot,'harness/migrations');
  const db=await HarnessDatabase.open({databasePath,migrationsDirectory,backupDirectory:path.join(root,'backups')});
  const now='2026-09-28T00:00:00.000Z';
  db.connection.prepare("INSERT INTO namespaces(namespace,status,version,created_at,updated_at) VALUES ('browser','ACTIVE',1,?,?)").run(now,now);
  for(let i=0;i<45;i++){
    const id='case_browser_'+String(i).padStart(3,'0');
    db.connection.prepare("INSERT INTO cases(case_id,namespace,current_version,status,title,summary,risk_level,created_at,updated_at) VALUES (?,'browser',1,'VALIDATED',?,'','LOW',?,?)").run(id,'真实分页用例 '+i,now,now);
    db.connection.prepare("INSERT INTO case_versions(case_id,version,definition_json,content_hash,created_by,created_at) VALUES (?,1,?,?,'TEST',?)").run(id,'{"domain":"PAYMENTS"}','a'.repeat(64),now);
  }
  await db.close();
  const started=await startHarness({productRoot,databasePath,migrationsDirectory,backupDirectory:path.join(root,'backups'),artifactRoot:path.join(root,'artifacts'),security:{serviceToken:'s'.repeat(32),allowedClients:['127.0.0.1']},schedulerIntervalMs:0,qualityPortalRoot:path.resolve(productRoot,'../../apps/quality-case-portal/dist'),host:'127.0.0.1',port:0});
  const browser=await chromium.launch({headless:true,executablePath:path.join(productRoot,'runtime/browsers/chromium-1217/chrome-win64/chrome.exe')});
  t.after(async()=>{await browser.close();await new Promise(r=>started.server.close(r));await started.application.close();fs.rmSync(root,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];const queries=[];
  page.on('pageerror',()=>errors.push('PAGE_ERROR'));
  page.on('console',m=>{if(m.type()==='error')errors.push('CONSOLE_ERROR');});
  page.on('request',r=>{if(new URL(r.url()).pathname==='/api/quality/v1/cases'){assert.equal(r.method(),'GET');assert.equal(r.headers().authorization,undefined);queries.push(new URL(r.url()).searchParams);}});
  const url=`http://127.0.0.1:${started.server.address().port}/quality/cases`;
  await page.goto(url);
  assert.match(await page.title(),/衡准/);
  await page.getByText('第 1 页 · 本页 20 项').waitFor();
  assert.equal(await page.locator('vite-error-overlay').count(),0);
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  await page.getByText('第 2 页 · 本页 20 项').waitFor();
  assert.ok(queries.some(q=>q.has('cursor')));
  await page.getByRole('button',{name:'上一页',exact:true}).click();
  await page.getByText('第 1 页 · 本页 20 项').waitFor();
  await page.getByPlaceholder('搜索编号、名称或业务域').fill('case_browser_044');
  await page.getByText('第 1 页 · 本页 1 项').waitFor();
  await page.getByRole('button',{name:'真实分页用例 44',exact:true}).waitFor();
  assert.ok(queries.some(q=>q.get('q')==='case_browser_044'));
  assert.deepEqual(errors,[]);
  const screenshot=path.join(os.tmpdir(),'rf057-quality-pagination-desktop.png');
  await page.screenshot({path:screenshot,fullPage:false});
  console.log(JSON.stringify({evidenceClass:'BROWSER_INTEGRATION',url,viewport:'1440x1000',browserPlugin:'ABSENT',checks:['PAGE_IDENTITY','NOT_BLANK','NO_OVERLAY','CONSOLE_HEALTH','CURSOR_NEXT_PREVIOUS','GLOBAL_SEARCH','READ_ONLY_NO_TOKEN'],screenshot}));
});
