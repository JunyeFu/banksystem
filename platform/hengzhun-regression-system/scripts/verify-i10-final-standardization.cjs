#!/usr/bin/env node
'use strict'

// Preflight for the final I10 acceptance campaign.  This is intentionally a
// code-and-contract gate, not a substitute for the later real 18-chain run.
// It fails before a run starts when a known replay guarantee has drifted.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const root = path.resolve(__dirname, '..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const json = relative => JSON.parse(read(relative))
const catalog = json('contracts/i10/case-catalog-v1.json')
const refs = json('contracts/i10/opaque-reference-v1.json')
const transition = json('contracts/i10/journey-transition-v2.json')
const manifest = json('flowise/i10/publication-manifest-v1.json')
const flow = json('flowise/i10/agentflow-v7.json')
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex')

assert.equal(catalog.schemaVersion, 'hengzhun-i10-case-catalog-v1')
assert.deepEqual(Object.keys(catalog.cases).sort(), ['H1','H2','H3','L1','L2','L3','M1','M2','M3'])
for (const id of ['L1','L2','L3']) assert.equal(catalog.cases[id].verificationPolicy, 'NONE', `${id}: verification policy drift`)
for (const id of ['H1','H2','H3']) {
  assert.equal(catalog.cases[id].verificationPolicy, 'AUTO_PERSISTED_UKEY', `${id}: UKey policy drift`)
  assert.deepEqual(catalog.cases[id].requiredInputs, ['payeeRef','amount','currency','purpose'], `${id}: typed transfer input drift`)
}
assert.equal(refs.references.candidate.suffixPattern, '[0-9a-f]{40}')
assert.ok(transition.actionKinds.includes('CONFIRM_EXACT'))
assert.equal(transition.rules.oneMutatingActionPerFlowiseExecution, true)
assert.equal(manifest.primaryFlowVersion, 7)
assert.equal(manifest.primaryFlowDataPath, 'flowise/i10/agentflow-v7.json')
assert.equal(manifest.primaryFlowSha256, sha256(read('flowise/i10/agentflow-v7.json')))
assert.equal(flow.i10Contract?.journeyTransitionVersion, 'JourneyTransitionV2')
assert.equal(flow.i10Contract?.acceptanceRecordVersion, 'AcceptanceRecordV3')
const interactionArgs = flow.nodes.flatMap(node => Array.isArray(node?.data?.inputs?.toolInputArgs) ? node.data.inputs.toolInputArgs : [])
  .filter(arg => arg?.inputArgName === 'interactionContractVersion')
assert.ok(interactionArgs.length > 0)
assert.ok(interactionArgs.every(arg => arg.inputArgValue === 'v6'))
const runner = read('scripts/i10-18-chain-acceptance-live.cjs')
assert.match(runner, /i10-acceptance-ledger-v3/)
assert.match(runner, /writeCheckpoint/)
assert.match(runner, /run-result\.json/)
assert.match(runner, /currentReleaseIdentity\(\)/)
assert.match(runner, /existingTerminal\(caseId, variant, attempt\)/)
assert.doesNotMatch(runner, /I10_ACCEPTANCE_FLOWISE_V6_NOT_DEPLOYED/)
const verification = read('worker/src/adapters/fuxing-bank-demo/verification-policy.cjs')
assert.match(verification, /attempt <= 3/)
assert.match(verification, /I10_UKEY_AUTOMATION_ATTEMPTS_EXHAUSTED/)
assert.match(verification, /I10_VERIFICATION_NOT_RESOLVED/)
const authoring = read('worker/src/i10-midscene-candidate-authoring.cjs')
assert.doesNotMatch(authoring, /body\.innerText\(\).*移动证书/s)
assert.ok(fs.existsSync(path.join(root, 'harness/migrations/033_i10_verification_attempts.sql')))
const normalizer = read('scripts/i10-case-draft-normalizer.cjs')
const harnessService = read('harness/src/service.ts')
assert.match(normalizer, /hengzhun-i10-typed-business-inputs-v1/)
assert.match(normalizer, /businessInput\.payeeRef/)
assert.match(harnessService, /I10_TYPED_BUSINESS_INPUT_REQUIRED/)
process.stdout.write('HENGZHUN_I10_FINAL_STANDARDIZATION_PREFLIGHT_OK\n')
