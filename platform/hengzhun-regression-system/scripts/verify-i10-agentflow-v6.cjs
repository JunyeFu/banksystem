#!/usr/bin/env node
'use strict'
const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')
const { validateAgentflow } = require('./verify-i10-agentflow-paths.cjs')

const root = path.resolve(__dirname, '..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const flow = JSON.parse(read('flowise/i10/agentflow-v6.json'))
const manifest = JSON.parse(read('flowise/i10/publication-manifest-v1.json'))
assert.deepEqual(validateAgentflow(flow), [], 'I10_V6_AGENTFLOW_PATH_INVALID')
assert.equal(flow.i10Contract.schemaVersion, 'hengzhun-i10-agentflow-v6')
assert.equal(flow.i10Contract.verificationPolicyVersion, 'VerificationPolicyV2')
assert.equal(manifest.primaryFlowDataPath, 'flowise/i10/agentflow-v6.json')
assert.equal(manifest.primaryFlowVersion, 6)
assert.equal(manifest.primaryFlowSha256, crypto.createHash('sha256').update(read('flowise/i10/agentflow-v6.json')).digest('hex'))
assert.equal(manifest.mcpToolCount, 33)
const byId = new Map(flow.nodes.map(node => [node.id, node]))
const hasEdge = (source, target, sourceHandle) => flow.edges.some(edge =>
  edge.source === source && edge.target === target &&
  (sourceHandle === undefined || edge.sourceHandle === sourceHandle)
)
const resultRoute = byId.get('conditionAgentflow_i10_v5_result_query_route')
assert.ok(resultRoute, 'I10_V6_RESULT_QUERY_ROUTE_MISSING')
assert.equal(resultRoute.data?.inputs?.conditions?.[0]?.value2, 'RESULT_QUERY')
assert.ok(hasEdge('customFunctionAgentflow_i10_v4_classification_merge', resultRoute.id), 'I10_V6_RESULT_QUERY_ROUTE_INPUT_MISSING')
assert.ok(hasEdge(resultRoute.id, 'toolAgentflow_i10_v3_result_inbox', `${resultRoute.id}-output-0`), 'I10_V6_RESULT_QUERY_INBOX_PATH_MISSING')
const scheduleDisableRoute = byId.get('conditionAgentflow_i10_v5_schedule_disable_route')
assert.ok(scheduleDisableRoute, 'I10_V6_SCHEDULE_DISABLE_ROUTE_MISSING')
assert.equal(scheduleDisableRoute.data?.inputs?.conditions?.[0]?.value2, 'SCHEDULE_DISABLE')
assert.ok(hasEdge(resultRoute.id, scheduleDisableRoute.id, `${resultRoute.id}-output-1`), 'I10_V6_RESULT_QUERY_CASE_FALLBACK_MISSING')
assert.ok(hasEdge(scheduleDisableRoute.id, 'humanInputAgentflow_schedule_disable', `${scheduleDisableRoute.id}-output-0`), 'I10_V6_SCHEDULE_DISABLE_CONFIRM_PATH_MISSING')
assert.ok(hasEdge('humanInputAgentflow_schedule_disable', 'toolAgentflow_i10_v3_schedule_disable', 'humanInputAgentflow_schedule_disable-output-0'), 'I10_V6_SCHEDULE_DISABLE_APPROVAL_PATH_MISSING')
const alreadyActiveRoute = byId.get('conditionAgentflow_i10_v6_candidate_on_demand_available')
assert.ok(alreadyActiveRoute, 'I10_V6_CANDIDATE_ON_DEMAND_ROUTE_MISSING')
assert.equal(alreadyActiveRoute.data?.inputs?.conditions?.[0]?.value2, 'ON_DEMAND_RUN_AVAILABLE')
assert.ok(hasEdge('conditionAgentflow_candidate_ready', alreadyActiveRoute.id, 'conditionAgentflow_candidate_ready-output-1'), 'I10_V6_CANDIDATE_ON_DEMAND_ROUTE_INPUT_MISSING')
assert.ok(hasEdge(alreadyActiveRoute.id, 'humanInputAgentflow_run', `${alreadyActiveRoute.id}-output-0`), 'I10_V6_CANDIDATE_ON_DEMAND_RUN_PATH_MISSING')
assert.ok(hasEdge(alreadyActiveRoute.id, 'conditionAgentflow_candidate_authoring_failed', `${alreadyActiveRoute.id}-output-1`), 'I10_V6_CANDIDATE_FAILURE_FALLBACK_MISSING')
process.stdout.write('HENGZHUN_I10_AGENTFLOW_V6_OK\n')
